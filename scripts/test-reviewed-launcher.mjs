// Exercise the actual launcher template against a disposable fake runtime.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const sha = (b) => createHash('sha256').update(b).digest('hex');
const dir = mkdtempSync(join(tmpdir(), 'yomi-launcher-test-'));
const release = join(dir, 'release');
mkdirSync(join(release, 'dist/mcp'), { recursive: true });
const server = join(release, 'dist/mcp/server.js');
const source = 'console.log(JSON.stringify({hasToken:!!process.env.GITHUB_TOKEN,hasNodeOptions:!!process.env.NODE_OPTIONS,noUpdate:process.env.YOMI_NO_UPDATE_CHECK}));\n';
writeFileSync(server, source);
const bytes = JSON.stringify({ revision: 'test', entries: { 'dist/mcp/server.js': { sha256: sha(source) } } });
const manifest = join(release, 'reviewed-integrity.json');
writeFileSync(manifest, bytes);
const launcher = join(dir, 'launch.mjs');
writeFileSync(launcher, readFileSync(fileURLToPath(new URL('./reviewed-launcher.template.mjs', import.meta.url)), 'utf8').replace('__RELEASE_PATH__', JSON.stringify(release)).replace('__MANIFEST_SHA256__', JSON.stringify(sha(bytes))));
const run = (args = ['--verify-only']) => spawnSync(process.execPath, [launcher, ...args], { encoding: 'utf8', env: { ...process.env, GITHUB_TOKEN: 'test-sentinel-only' } });
assert.equal(run().status, 0);
writeFileSync(server, source + '// changed');
assert.notEqual(run().status, 0);
writeFileSync(server, source);
writeFileSync(join(release, 'dist/unreviewed.js'), '');
assert.notEqual(run().status, 0);
unlinkSync(join(release, 'dist/unreviewed.js'));
unlinkSync(server);
assert.notEqual(run().status, 0);
writeFileSync(server, source);
writeFileSync(manifest, bytes + '\n');
assert.notEqual(run().status, 0);
writeFileSync(manifest, bytes);
const launched = run(['--smoke']);
assert.equal(launched.status, 0, launched.stderr);
assert.deepEqual(JSON.parse(launched.stdout), { hasToken: false, hasNodeOptions: false, noUpdate: '1' });
console.log('Launcher checks passed: changed, added, missing and altered-manifest files refused; child environment scrubbed.');
